// Firenze 30h: validates cloning, preserved Pistoia guide and absence of accounting quizzes.
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'../app/blueprints/guida/static/esercizi');
function load(name,ctx){vm.runInNewContext(fs.readFileSync(path.join(root,name),'utf8'),ctx,{filename:name,timeout:6000})}
const pistoia={window:{}};
load('magazziniere-5.js',pistoia);
const source=pistoia.window.MSA_ESERCIZIO;
assert.equal(source.codice,'magazziniere-5');
assert.equal(source.passi.length,82);
assert.equal(source.verificaRagioneria,true);
assert(source.passi.some(p=>p.titolo==='Libro giornale: la storia contabile del magazzino'));
const firenze={window:{}};
load('magazziniere-5.js',firenze);
load('firenze-30.js',firenze);
const e=firenze.window.MSA_ESERCIZIO;
assert.equal(e.codice,'firenze-30');
assert.equal(e.passi.length,80);
assert.equal(e.verificaRagioneria,false);
assert(e.passi.every(p=>p.punti&&p.punti.length>0));
assert(e.passi.every(p=>!p.contabile));
assert(e.passi.some(p=>p.titolo.startsWith('VA01: Beta')));
assert(e.passi.some(p=>p.titolo.startsWith('ME21N:')));
assert(e.passi.some(p=>p.titolo.startsWith('CO01:')));
assert(e.passi.some(p=>p.titolo.startsWith('RF: preleva')));
assert(e.passi.some(p=>p.titolo.startsWith('Varco RFID')));
assert(e.passi.some(p=>p.titolo.startsWith('KPI di magazzino')));
assert(!e.passi.some(p=>p.titolo.startsWith('Libro giornale:')));
const first=e.passi[0];
assert.equal(first.punti.find(p=>p.sel==='#lg-quiz').valore,'no');
assert(first.fatto({S:{percorso:'logistica', quizContabile:false}}));
assert(!first.fatto({S:{percorso:'logistica'}}),'Reject accounting-enabled logistics account');
assert(!first.fatto({S:{percorso:'negozio', quizContabile:false}}));
assert(!e.passi.some(p=>p.punti.some(d=>/ricostruzione contabile|ricostruisci Dare|libro giornale|scrittura di apertura/i.test(d.serve||''))));
const finalStep=e.passi.find(p=>p.titolo.startsWith('Consegna l’esercitazione'));
assert.equal(finalStep.dove.esercizio,'firenze-30','Final submission opens Firenze assignment');
const exercises=fs.readFileSync(path.join(__dirname,'../app/esercizi.py'),'utf8');
assert(exercises.includes('ESERCIZI["firenze-30"]'),'Firenze is a distinct deliverable');
assert(exercises.includes('"mg_colli"')&&exercises.includes('"quadratura_im_wm"'),'Operational assessment included');
const submission=fs.readFileSync(path.join(__dirname,'../app/blueprints/allievo/templates/allievo/consegna.html'),'utf8');
assert(submission.includes("request.args.get('esercizio') == k"),'Exercise auto-selected in submission form');
const panel=fs.readFileSync(path.join(__dirname,'../app/blueprints/guida/static/pannello.js'),'utf8');
assert(panel.includes("if (E.codice === 'firenze-30') return s;"),'No implicit checkmarks for Firenze');

assert.equal(pistoia.window.MSA_ESERCIZIO.passi.length,82,'Original unaffected by Firenze import');
const cfg=fs.readFileSync(path.join(__dirname,'../app/blueprints/guida/__init__.py'),'utf8');
assert(cfg.includes('"firenze-30"'));
const tpl=fs.readFileSync(path.join(__dirname,'../app/blueprints/guida/templates/guida/_pannello.html'),'utf8');
assert(tpl.includes("esercizi/magazziniere-5.js"));
const launch=fs.readFileSync(path.join(__dirname,'../app/blueprints/portale/templates/portale/launchpad.html'),'utf8');
assert(launch.includes("esercizio_guida='firenze-30'"));
const start=fs.readFileSync(path.join(__dirname,'../app/blueprints/erp_dati/static/dati-pagine.js'),'utf8');
assert(start.includes("firenze30 ? 'no' : 'si'"));
assert(start.includes("if (firenze30) v.quiz = 'no'"));
console.log('OK Firenze: 80 guided operational steps, quiz off, launchpad, startup and untouched Pistoia 82 steps');
